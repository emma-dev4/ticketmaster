type Seed = Omit<EventItem, "aboutEn" | "aboutEs" | "ageEn" | "ageEs" | "label"> & {
  label?: MapLabel;
  ageEn?: string;
  ageEs?: string;
  extraEn: string;
  extraEs: string;
};

function ev(p: Seed): EventItem {
  const { extraEn, extraEs, label, ageEn, ageEs, ...rest } = p;
  return {
    ...rest,
    label: label ?? "STAGE",
    ageEn: ageEn ?? "All ages",
    ageEs: ageEs ?? "Todos los públicos",
    aboutEn: `${extraEn} All-in prices, mobile entry, and an interactive seat map. Standard, Official Platinum, VIP, and Verified Resale tickets are listed together.`,
    aboutEs: `${extraEs} Precios con gastos incluidos, entrada móvil y mapa de asientos interactivo. Entradas estándar, Official Platinum, VIP y reventa verificada en el mismo listado.`,
  };
}

const nights = (
  id: string,
  dates: string[],
  base: Omit<Seed, "id" | "date" | "extraEn" | "extraEs"> & { extraEn: string; extraEs: string },
): EventItem[] =>
  dates.map((date, i) =>
    ev({
      ...base,
      id: dates.length > 1 ? `${id}-${i + 1}` : id,
      date,
      extraEn: dates.length > 1 ? `${base.extraEn} Performance ${i + 1}.` : base.extraEn,
      extraEs: dates.length > 1 ? `${base.extraEs} Función ${i + 1}.` : base.extraEs,
    }),
  );

