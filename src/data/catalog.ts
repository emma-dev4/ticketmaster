export function artistBy(slug: string) {
  return artists.find((a) => a.slug === slug);
}

export function getEvent(id: string) {
  return events.find((e) => e.id === id);
}

export function byDate(a: EventItem, b: EventItem) {
  return +new Date(a.date) - +new Date(b.date);
}

export function placeLine(e: EventItem) {
  return e.market === "us" ? `${e.city}, ${e.region}` : e.city;
}

export type SalePhase = "open" | "wait" | "code";

export function salePhase(event: EventItem, unlocked: string[], now = Date.now()): SalePhase {
  if (!event.presaleStart) return "open";
  if (now < new Date(event.presaleStart).getTime()) return "wait";
  if (event.publicOn && now >= new Date(event.publicOn).getTime()) return "open";
  if (unlocked.includes(event.id)) return "open";
  return "code";
}

